type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

const fallbackLanguageContext: LanguageContextValue = {
  language: "zh",
  setLanguage: () => undefined,
  t: (key, values) => Object.entries(values ?? {}).reduce(
    (text, [name, replacement]) => text.replaceAll(`{{${name}}}`, String(replacement)),
    zh[key] ?? key,
  ),
};

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("zh");

  useEffect(() => {
    const timer = window.setTimeout(() => {
      const saved = window.localStorage.getItem(LANGUAGE_KEY);
      if (saved === "zh" || saved === "en") setLanguageState(saved);
    }, 0);
    return () => window.clearTimeout(timer);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language === "en" ? "en" : "zh-CN";
  }, [language]);

  const setLanguage = (next: Language) => {
    setLanguageState(next);
    window.localStorage.setItem(LANGUAGE_KEY, next);
  };

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (key, values) => {
      const translated = (language === "en" ? en : zh)[key] ?? key;
      return Object.entries(values ?? {}).reduce(
        (text, [name, replacement]) => text.replaceAll(`{{${name}}}`, String(replacement)),
        translated,
      );
    },
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext) ?? fallbackLanguageContext;
}

export function LanguageSwitcher() {
  const { language, setLanguage, t } = useLanguage();
  return (
    <label className="language-switcher">
      <span>{t("语言")}</span>
      <select aria-label={t("语言")} value={language} onChange={(event) => setLanguage(event.target.value as Language)}>
        <option value="zh">{t("中文")}</option>
        <option value="en">{t("English")}</option>
      </select>
    </label>
  );
}
